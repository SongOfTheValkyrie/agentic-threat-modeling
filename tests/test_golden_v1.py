"""Gate G1: logging-only changes must not alter behavior (V2_SPEC.md §10).

The fixture ``fixtures/golden_v1.json`` was generated by ``golden_support.py``
from the tree archived from git tag ``v1-benchmark``, i.e. from code that had no
V2 logging. These tests run the same harness on the working tree and require
identical results:

* the threats each approach returns,
* a hash of every request sent to the (stubbed) LLM, which fixes the exact
  prompt text, the number of calls, and their order,
* usage counters and the agent traces.

The only permitted difference is the two additive trace fields listed in
``ADDED_ELEMENT_KEYS``. Everything is offline: a deterministic stub replaces the
model, so no Ollama server is needed. Independent live Ollama runs are not
expected to match each other and are not tested here.
"""

import copy
import json
import re
from pathlib import Path

import golden_support as gs
import pytest

from src.agent import structured
from src.models.loader import load_architecture
from src.RAG.knowledge import load_knowledge_base
from src.RAG.retriever import KeywordRetriever

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "golden_v1.json"
MANIFEST = ROOT / "frozen" / "v1" / "MANIFEST.md"

# The only trace fields the V2 logging change is allowed to add.
ADDED_ELEMENT_KEYS = ("proposed_threats", "confirmed_threats")

LABELS = [label for label, _ in gs.SPECS]
PEV_LABELS = [label for label in LABELS if label.startswith("agent_pev")]
NO_VERIFY_LABELS = {"agent_pev_noverify", "agent_pev_explore_only"}
CASES = [(arch, label) for arch in gs.ARCHITECTURES for label in LABELS]
PEV_CASES = [(arch, label) for arch in gs.ARCHITECTURES for label in PEV_LABELS]

# Files that must stay byte-identical to V1 while the V2 evaluation basis is
# built: matching, retrieval, and the prompts of RAG and the free agent. The
# PEV module is excluded because logging legitimately edited it; its prompts
# are protected by the request hashes compared below instead.
UNCHANGED_SINCE_V1 = [f for f in gs.PROVENANCE_FILES if f != "src/agent/structured.py"]


@pytest.fixture(scope="module")
def golden() -> dict:
    return json.loads(FIXTURE.read_text())


@pytest.fixture(scope="module")
def actual() -> dict:
    return gs.run_all(ROOT)


def _strip_added(trace: dict | None) -> dict | None:
    """Remove exactly the permitted additive fields from a PEV trace copy."""
    if trace is None or "elements" not in trace:
        return trace
    stripped = copy.deepcopy(trace)
    for element in stripped["elements"]:
        for key in ADDED_ELEMENT_KEYS:
            element.pop(key, None)
    return stripped


def _manifest_checksums() -> dict[str, str]:
    return dict(re.findall(r"\| `([^`]+)` \| `([0-9a-f]{16})` \|", MANIFEST.read_text()))


# --- equivalence with the V1 golden fixture ---------------------------------


@pytest.mark.parametrize(("arch", "label"), CASES)
def test_run_matches_v1_golden(arch, label, golden, actual):
    want = golden["runs"][arch][label]
    got = actual[arch][label]
    assert got["modeler_name"] == want["modeler_name"]
    assert got["threats"] == want["threats"]
    # Exact prompts, number of LLM calls, and their order.
    assert got["requests"] == want["requests"]
    assert got["llm_calls"] == want["llm_calls"]
    assert got["retrieval_calls"] == want["retrieval_calls"]
    assert _strip_added(got["trace"]) == want["trace"]


def test_fixture_covers_every_variant_and_architecture(golden):
    assert sorted(golden["runs"]) == sorted(gs.ARCHITECTURES)
    for arch in gs.ARCHITECTURES:
        assert sorted(golden["runs"][arch]) == sorted(LABELS)


def test_fixture_has_no_unclassified_requests(golden):
    phases = {
        req["phase"]
        for by_label in golden["runs"].values()
        for run in by_label.values()
        for req in run["requests"]
    }
    assert "unclassified" not in phases
    # The stub exercised every phase the approaches use.
    assert {"rag", "agent", "pev_plan", "pev_deepen", "pev_explore", "pev_verify"} <= phases


# --- the harness is sensitive to behavior changes ---------------------------


def test_harness_detects_a_one_character_prompt_change(monkeypatch, golden):
    """Negative control: a trailing space in one prompt must be caught."""
    monkeypatch.setattr(structured, "EXPLORE_PROMPT", structured.EXPLORE_PROMPT + " ")
    architecture = load_architecture(ROOT / "benchmark" / "simple_web_api.json")
    retriever = KeywordRetriever(load_knowledge_base(ROOT / "data" / "knowledge_base.json"))
    got = gs.run_one(dict(gs.SPECS)["agent_pev"], architecture, retriever)
    want = golden["runs"]["simple_web_api"]["agent_pev"]

    assert len(got["requests"]) == len(want["requests"])
    differing = {
        got["requests"][i]["phase"]
        for i, (a, b) in enumerate(zip(got["requests"], want["requests"], strict=True))
        if a != b
    }
    # Only the explore requests changed, and the change was detected.
    assert differing == {"pev_explore"}


