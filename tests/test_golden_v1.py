# --- the additive trace fields ----------------------------------------------


@pytest.mark.parametrize(("arch", "label"), PEV_CASES)
def test_added_trace_fields_are_consistent_with_existing_ones(arch, label, actual):
    trace = actual[arch][label]["trace"]
    assert trace["elements"], "expected at least one element record"
    for element in trace["elements"]:
        proposed = element["proposed_threats"]
        confirmed = element["confirmed_threats"]
        element_id = element["element_id"]

        assert len(proposed) == element["proposed"]
        assert len(confirmed) == element["confirmed"]
        # The existing key fields are derived from the same lists.
        assert sorted({f"{element_id}:{c['category']}" for c in proposed}) == element[
            "proposed_keys"
        ]
        assert sorted({f"{element_id}:{c['category']}" for c in confirmed}) == element[
            "confirmed_keys"
        ]
        for candidate in proposed + confirmed:
            assert set(candidate) == {"category", "description", "mitigation"}
        if label in NO_VERIFY_LABELS:
            assert confirmed == proposed


@pytest.mark.parametrize(("arch", "label"), PEV_CASES)
def test_logged_candidates_equal_returned_threats(arch, label, actual):
    """The confirmed texts in the trace are exactly what the run returned."""
    run = actual[arch][label]
    logged = [
        (e["element_id"], c["category"], c["description"], c["mitigation"])
        for e in run["trace"]["elements"]
        for c in e["confirmed_threats"]
    ]
    returned = [
        (t["component_id"] or t["data_flow_id"], t["category"], t["description"], t["mitigation"])
        for t in run["threats"]
    ]
    assert logged == returned
